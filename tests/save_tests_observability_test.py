def _step_block(name: str, expect_status: int) -> str:
    """生一个「GET /status/200 + eq status_code」的 teststep YAML 块。"""
    return (
        f"    -\n"
        f"        name: {name}\n"
        f"        request:\n"
        f"            method: GET\n"
        f"            url: /status/200\n"
        f"        validate:\n"
        f'            - eq: ["status_code", {expect_status}]\n'
    )


class TestFailedCaseIsNotReportedAsSuccess(unittest.TestCase):
    """H1 端到端：走真 CLI（`hrun run case.yml --save-tests`）核对 summary.json。

    ## 修复前的现场（实测，2 步用例、第 2 步断言 `status_code == 999`）

    ```text
    内层 pytest：1 failed、子进程退出码 1        ← 唯一没说谎的地方
    logs/case.summary.json：
      success = True
      stat    = {'testcases': {'total': 1, 'success': 1, 'fail': 0},
                 'teststeps': {'total': 1, 'failures': 0, 'successes': 1}}
      details[0].success = True
      details[0].records = [只有 step1]          ← 失败那一步整体消失
    ```

    两处根因（都在 `runner.py`，见 `__failed` / `__record_failed_step` 的 NOTICE）：

    1. `__run_step` 在重试耗尽时直接 `raise`，**跳过** `__step_results.append(step_result)`
       ——失败那一步的 `data`（`validators` + 请求响应记录）随异常一起被丢掉；
    2. `get_summary()` 的 `summary_success` **只**由 `__step_results` 推导，
       「本用例抛过异常」这个事实完全不参与。

    现在：三个 step 模块把已建好的 `StepResult` 挂在异常上交给 runner，runner 记录它；
    另外 `__failed` 作为用例级事实来源参与 `summary_success`。
    """

    def setUp(self):
        self.tmp_dir, self.yml_path = _make_tmp_project()

    def tearDown(self):
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    def _run_save_tests(self, steps_yaml: str):
        """写用例 → 真 CLI 跑 → 返回 (proc, summary.json 内容)。"""
        with open(self.yml_path, "w", encoding="utf-8") as f:
            f.write(
                f"config:\n"
                f"    name: h1 probe\n"
                f"    base_url: {HTTP_BIN_URL}\n"
                f"teststeps:\n"
                f"{steps_yaml}"
            )

        env = dict(os.environ)
        env["PYTHONIOENCODING"] = "utf-8"
        proc = subprocess.run(
            [
                sys.executable,
                "-m",
                "interfacetester",
                "run",
                "case.yml",
                "--save-tests",
            ],
            cwd=self.tmp_dir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            timeout=180,
        )

        summary_path = os.path.join(self.tmp_dir, "logs", "case.summary.json")
        self.assertTrue(
            os.path.isfile(summary_path),
            f"summary.json 没有被生成\nreturncode={proc.returncode}\n"
            f"stdout=\n{proc.stdout}\nstderr=\n{proc.stderr}",
        )
        with open(summary_path, encoding="utf-8") as f:
            return proc, json.load(f)

    def test_failed_case_is_not_reported_as_success(self):
        """三处（`success` / `stat.testcases` / `details[].success`）都不能说谎。"""
        proc, summary = self._run_save_tests(
            _step_block("step1 ok", 200) + _step_block("step2 WILL FAIL", 999)
        )

        self.assertNotEqual(proc.returncode, 0, "失败用例不该返回 0")
        self.assertFalse(
            summary["success"], f"失败用例被报成通过（H1）：{json.dumps(summary, ensure_ascii=False)[:400]}"
        )
        self.assertEqual(
            summary["stat"]["testcases"], {"total": 1, "success": 0, "fail": 1}
        )
        self.assertFalse(summary["details"][0]["success"])

    def test_step_counts_include_the_failed_step(self):
        """`stat.teststeps` 必须把失败那一步算进去（修复前 total 少算一步）。"""
        _proc, summary = self._run_save_tests(
            _step_block("step1 ok", 200) + _step_block("step2 WILL FAIL", 999)
        )

        self.assertEqual(
            summary["stat"]["teststeps"],
            {"total": 2, "failures": 1, "successes": 1},
            "失败步骤没有进统计（消费方 compat.py 的 `len(step_results) - 1` 算法会因此错位）",
        )

    def test_failing_step_stays_in_records_with_its_evidence(self):
        """失败那一步必须在 `records` 里，且带着「哪条断言挂了」的证据。"""
        _proc, summary = self._run_save_tests(
            _step_block("step1 ok", 200) + _step_block("step2 WILL FAIL", 999)
        )

        records = summary["details"][0]["records"]
        self.assertEqual(
            [record["name"] for record in records],
            ["step1 ok", "step2 WILL FAIL"],
            f"失败那一步没进报告：{records}",
        )

        failing = records[-1]
        self.assertFalse(failing["success"])
        # 证据一：断言结果（修复前它与 StepResult 一起被丢掉）
        validators = failing["data"]["validators"]["validate_extractor"]
        self.assertEqual(validators[0]["check_result"], "fail")
        self.assertEqual(validators[0]["expect_value"], 999)
        self.assertEqual(validators[0]["check_value"], 200)
        # 证据二：这一次的请求/响应记录
        self.assertEqual(failing["data"]["success"], False)
        self.assertEqual(len(failing["data"]["req_resps"]), 1)
        self.assertEqual(
            failing["data"]["req_resps"][0]["response"]["status_code"], 200
        )

    def test_single_step_failure_still_counts_one_step(self):
        """单步用例失败：修复前 `teststeps.total` 是 **0**（列表为空）。"""
        proc, summary = self._run_save_tests(_step_block("only step fails", 999))

        self.assertNotEqual(proc.returncode, 0)
        self.assertFalse(summary["success"])
        self.assertEqual(
            summary["stat"]["teststeps"],
            {"total": 1, "failures": 1, "successes": 0},
        )
        self.assertEqual(
            [record["name"] for record in summary["details"][0]["records"]],
            ["only step fails"],
        )


class TestFailedCaseSummaryObject(unittest.TestCase):
    """单元级（不落盘）：失败之后 `get_summary()` 本身也不能说「通过」。

    `compat.py` 的 `--save-tests` 装置就是在用例失败之后调用 `get_summary()` 的，
    所以这一层必须自己站得住，不能只依赖 summary.json 的端到端用例。
    """

    def test_get_summary_is_not_successful_after_a_step_fails(self):
        class _FailOnSecond(InterfaceTester):
            config = Config("h1 unit probe").base_url(HTTP_BIN_URL)
            teststeps = [
                Step(
                    RunRequest("first ok")
                    .get("/status/200")
                    .validate()
                    .assert_equal("status_code", 200)
                ),
                Step(
                    RunRequest("second fails")
                    .get("/status/200")
                    .validate()
                    .assert_equal("status_code", 999)
                ),
            ]

        case = _FailOnSecond()
        with self.assertRaises(exceptions.ValidationFailure):
            case.test_start()

        summary = case.get_summary()
        self.assertFalse(summary.success, "失败用例的 summary.success 不能是 True（H1）")
        self.assertEqual(
            [step_result.name for step_result in summary.step_results],
            ["first ok", "second fails"],
            "失败的那一步必须留在 step_results 里",
        )
        self.assertFalse(summary.step_results[-1].success)
        self.assertIsNotNone(summary.step_results[-1].data)

    def test_failure_outside_any_step_is_still_not_successful(self):
        """用例级事实来源：异常发生在 step 之外（一步都没跑）时也要报失败。

        这一条覆盖的正是「只靠 `__step_results` 推导」修不好的那半边：
        列表是空的，但用例确实失败了。
        """

        class _BrokenSteps(InterfaceTester):
            config = Config("h1 no-step probe").base_url(HTTP_BIN_URL)

            @property
            def teststeps(self):
                raise exceptions.ParamsError("steps 装配失败（模拟 step 之外的异常）")

        case = _BrokenSteps()
        with self.assertRaises(exceptions.ParamsError):
            case.test_start()

        summary = case.get_summary()
        self.assertFalse(
            summary.success,
            "一步都没跑但抛了异常 → 不能报成功（修复前这里会是 success=True）",
        )
        self.assertEqual(summary.step_results, [])


