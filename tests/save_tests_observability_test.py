class TestStepResultRecordFieldsAreHonest(unittest.TestCase):
    """M7：`StepResult.content_size` 与失败 step 的 `step_type` 必须是真的。

    修复前（实测 `.tmp_audit/kernel/p1`，summary.json 的 records）：

    ```text
    { "name": "步骤1（GET /ok）", "step_type": "request", "success": true,
      "elapsed": 0.0075, "content_size": 0, "export_vars": {}, "attachment": "" }
    # 同一条记录里的 data.stat：
    {"content_size": 44, ...}          ← 同一条记录内部自相矛盾（0 vs 44）
    ```

    - `content_size` **全仓没有任何写入点**（`client.py` 写的是
      `SessionData.stat.content_size`，那是另一个字段）；
    - 失败 step 的 `step_type` 来自 `step.type()`，而它写的是
      `f"request-{MethodEnum.GET}"` —— Python 3.11+ 下 `f"{枚举}"` 得到
      **`MethodEnum.GET`**（不是 `GET`），于是报告里出现 `request-MethodEnum.GET`。
    """

    def _run_pass_case(self):
        class _OkCase(InterfaceTester):
            config = Config("m7 probe").base_url(HTTP_BIN_URL)
            teststeps = [
                Step(
                    # NOTICE: 必须选一个**响应体非空**的端点：mock 的 `/status/200`
                    # 返回空体（`Content-Length: 0`），用它断言不出「0 vs 真实值」这个矛盾。
                    RunRequest("simple get")
                    .get("/get")
                    .validate()
                    .assert_equal("status_code", 200)
                )
            ]

        case = _OkCase()
        case.test_start()
        return case.get_summary()

    def test_content_size_is_recorded_not_zero(self):
        summary = self._run_pass_case()
        step_result = summary.step_results[0]

        self.assertGreater(
            step_result.content_size,
            0,
            "StepResult.content_size 恒为 0（M7 修复前形态）",
        )
        # 与同一记录里的 data.stat 口径一致（这条才是真正的护栏：
        # 单独看 0 无害，**两个字段互相矛盾**才是「假数据」）
        self.assertEqual(
            step_result.content_size,
            step_result.data.stat.content_size,
            "content_size 与 data.stat.content_size 口径不一致",
        )

    def test_failed_request_step_type_has_no_enum_repr(self):
        class _FailCase(InterfaceTester):
            config = Config("m7 step_type probe").base_url(HTTP_BIN_URL)
            teststeps = [
                Step(
                    RunRequest("will fail")
                    .get("/status/200")
                    .validate()
                    .assert_equal("status_code", 999)
                )
            ]

        case = _FailCase()
        with self.assertRaises(exceptions.ValidationFailure):
            case.test_start()

        summary = case.get_summary()
        step_type = summary.step_results[-1].step_type

        self.assertNotIn(
            "MethodEnum",
            step_type,
            f"step_type 泄漏了枚举 repr（M7 修复前形态）：{step_type!r}",
        )
        self.assertEqual(step_type, "request-GET")

    def test_successful_request_step_type_is_unchanged(self):
        """反向护栏：**成功**路径的 `step_type`（`"request"`）逐字不变。

        SQL/thrift 两个模块同样是「成功记短名（`sql`/`thrift`）、失败记富名
        （`sql-request-…`/`thrift-request-…`）」，那是 0919-18 有意建立的口径
        （`tests/step_sql_request_test.py` 有护栏钉住失败侧的富名）。
        本次只修「枚举 repr 泄漏」，不动这个约定。
        """
        summary = self._run_pass_case()
        self.assertEqual(summary.step_results[0].step_type, "request")


