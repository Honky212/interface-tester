class TestMissingExportVariableDoesNotBreakSummary(unittest.TestCase):
    """H4：`get_summary()`（**报告路径**）不得因为导出变量缺失而抛异常。

    严格检查本身是对的，但它属于**运行时变量传递**那条路径
    （`step_testcase.run_step_testcase` 要把被引用用例的变量带给外层 step）；
    报告路径不该因为一个变量没导出就整个崩掉——那会连带丢掉整份 summary。
    """

    def setUp(self):
        loader.reset_project_meta()

    def tearDown(self):
        loader.reset_project_meta()

    def _run_case_with_declared_export(self, export_names):
        """跑一个**会通过**的用例，但 `config.export` 声明了从未被 extract 的变量。"""

        class _ExportProbeCase(InterfaceTester):
            config = Config("export probe").base_url(HTTP_BIN_URL).export(*export_names)
            teststeps = [
                Step(
                    RunRequest("ok step")
                    .get("/status/200")
                    .validate()
                    .assert_equal("status_code", 200)
                )
            ]

        return _ExportProbeCase().test_start()

    def test_get_summary_does_not_raise(self):
        """核心回归：`get_summary()` 不能抛 `ParamsError`。

        修复前它抛 `ParamsError: failed to export variable ...`，而这个异常发生在
        `session_fixture` 的 **teardown** 里 —— 于是每个用例都被记一个 ERROR，
        退出码变 1，`summary.json` 也不会被写出来。
        """
        runner = self._run_case_with_declared_export(["never_set_var"])

        summary = runner.get_summary()  # 修复前：这里抛 ParamsError

        self.assertTrue(summary.success, "用例本身是通过的，汇总也应当记为成功")
        self.assertEqual(summary.in_out.export_vars, {})
        self.assertEqual(len(summary.step_results), 1)

    def test_missing_export_is_reported_as_warning(self):
        """不能静默吞掉——缺失的导出变量必须留下告警（否则是另一种"丢证据"）。"""
        runner = self._run_case_with_declared_export(["never_set_var"])

        messages = _capture_warnings(runner.get_summary)

        self.assertTrue(
            any("never_set_var" in message for message in messages),
            f"缺失的导出变量没有被报告出来：{messages}",
        )

    def test_present_export_variable_is_still_exported(self):
        """反向断言：能导出的变量照旧导出（不能因为"宽松"就把功能改没了）。

        NOTICE（0919-13 / 批次 E）：这里断言的是**运行期取值**（`get_export_variables`）。
        修复前 `summary.in_out.export_vars` **就是**运行期取值源，所以当时直接断言 summary；
        现在 summary 里的是**脱敏后的展示副本**（`token` 命中 `SENSITIVE_KEYWORDS`，
        显示为 `******`）——两者必须分开断言，混在一起就会把
        「运行期取到了真值」和「报告里没有明文」两件事都测不出来。
        """

        class _GoodExportCase(InterfaceTester):
            config = Config("good export").base_url(HTTP_BIN_URL).export("token")
            teststeps = [
                Step(
                    RunRequest("extract then export")
                    .get("/status/200")
                    .extract()
                    .with_jmespath("status_code", "token")
                    .validate()
                    .assert_equal("status_code", 200)
                )
            ]

        runner = _GoodExportCase().test_start()

        # 运行期：真值（变量传递要靠它）
        self.assertEqual(runner.get_export_variables(strict=True), {"token": 200})
        # 展示副本：敏感键名脱敏（summary.json / HTML 报告里不该有明文）
        self.assertEqual(runner.get_summary().in_out.export_vars, {"token": "******"})

    def test_referenced_testcase_export_is_still_strict(self):
        """**反向断言（最重要的一条）**：变量传递路径必须保持严格。

        被引用用例声明了 `export` 却没真的导出 → 外层 step 的契约没被满足，
        必须**响亮地失败**，不能因为报告路径放宽了就把这条也一起放过去。
        """

        class _RefCase(InterfaceTester):
            config = Config("referenced case").base_url(HTTP_BIN_URL).export(
                "never_set_var"
            )
            teststeps = [
                Step(
                    RunRequest("ref step")
                    .get("/status/200")
                    .validate()
                    .assert_equal("status_code", 200)
                )
            ]

        class _ReferringCase(InterfaceTester):
            config = Config("referring case").base_url(HTTP_BIN_URL)
            teststeps = [Step(RunTestCase("call ref").call(_RefCase))]

        with self.assertRaises(Exception) as ctx:
            _ReferringCase().test_start()

        self.assertIn("never_set_var", str(ctx.exception))


class TestSaveTestsSummaryJsonIsWritten(unittest.TestCase):
    """H4 端到端：`hrun --save-tests` 必须**真的产出** summary.json。

    用子进程跑，因为它才是用户的真实路径（`main_run` → `ensure_cli_args` →
    `pytest.main`），也避免同进程嵌套 pytest 会话的不稳定（见 tests/cli_test.py 的 NOTES）。
    """

    def setUp(self):
        self.tmp_dir, self.yml_path = _make_tmp_project()

    def tearDown(self):
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    def _write_case_with_declared_export(self):
        with open(self.yml_path, "w", encoding="utf-8") as f:
            f.write(
                f"config:\n"
                f"    name: summary probe\n"
                f"    base_url: {HTTP_BIN_URL}\n"
                f"    export:\n"
                f"        - never_set_var\n"
                f"teststeps:\n"
                f"    -\n"
                f"        name: simple get\n"
                f"        request:\n"
                f"            method: GET\n"
                f"            url: /status/200\n"
                f"        validate:\n"
                f'            - eq: ["status_code", 200]\n'
            )

    def test_summary_json_is_written_and_exit_code_is_zero(self):
        self._write_case_with_declared_export()

        # NOTICE（0918-8 / L28）：子进程是**框架自己的 CLI**，它会把自己 stdout/stderr
        # 强制成 UTF-8（M10/L27）→ 父进程必须显式按 UTF-8 解码。
        # 修复前这里用 `text=True`（按 locale 解码，本机 cp936）：CJK locale 下
        # 读取线程会抛 UnicodeDecodeError、`proc.stdout` 变成 **None**，
        # 而 `f"{proc.stdout}"` 打印出来是 "None"——排查时看不到任何真实输出。
        env = dict(os.environ)
        env["PYTHONIOENCODING"] = "utf-8"
        proc = subprocess.run(
            [
                sys.executable,
                "-m",
                "interfacetester",
                "run",
                "case.yml",
                "--save-tests",
            ],
            cwd=self.tmp_dir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            timeout=180,
        )

        summary_path = os.path.join(self.tmp_dir, "logs", "case.summary.json")

        self.assertTrue(
            os.path.isfile(summary_path),
            f"summary.json 没有被生成（H4）\n"
            f"returncode={proc.returncode}\nstdout=\n{proc.stdout}\nstderr=\n{proc.stderr}",
        )
        self.assertEqual(
            proc.returncode, 0, f"用例通过却返回非 0：\n{proc.stdout}\n{proc.stderr}"
        )

        with open(summary_path, encoding="utf-8") as f:
            summary = json.load(f)

        self.assertTrue(summary["success"])
        self.assertEqual(summary["stat"]["testcases"]["total"], 1)
        self.assertEqual(summary["stat"]["testcases"]["fail"], 0)


