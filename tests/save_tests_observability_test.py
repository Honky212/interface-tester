class TestSaveTestsPathAndLocation(unittest.TestCase):
    """M3：判据不能是「这个 token 存在」，而是「上一个 token 是不是取值的选项」。

    ## 修复前的现场（实测三组，退出码全是 0）

    ```text
    hrun -c pytest.ini case.yml --save-tests            → logs/pytest.summary.json
    hrun --junitxml reports/out.xml case.yml --save-tests → logs/reports/out.summary.json
    hrun -c sub/pytest.ini case.yml --save-tests        → 在 sub/ 写 conftest.py，**不产出** summary
    ```

    根因：`_generate_conftest_for_summary` 用 `for arg in args: if os.path.exists(arg): break`
    猜用例路径，而**选项的值**本身也可以是存在的路径。同一份判据在 `cli.main_run` 里
    早就有了（批次 7 / M2），但那个调用点没复用它 —— 现在收口成
    `compat.filter_test_paths` + `compat.PYTEST_OPTIONS_WITH_VALUE` **唯一一份**。

    M4：找不到项目标记时，**不许**写到祖先目录（`load_project_meta` 会兜底成
    「当前已加载的 meta / cwd」）—— 实测把 conftest.py 写到了**仓库根**，
    而它里面的 `summary_path` 是硬编码的，会连带劫持同目录树下其它 pytest 会话的汇总输出。
    """

    def setUp(self):
        loader.reset_project_meta()
        self.tmp_dir, self.yml_path = _make_tmp_project()

    def tearDown(self):
        loader.reset_project_meta()
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    # ---------------------------------------------------------------- M3 单元
    def test_option_value_is_not_treated_as_a_test_path(self):
        ini_path = os.path.join(self.tmp_dir, "pytest.ini")
        with open(ini_path, "w", encoding="utf-8") as f:
            f.write("[pytest]\naddopts = -q\n")

        test_paths, remaining = compat.filter_test_paths(
            ["-c", ini_path, self.yml_path, "--save-tests"]
        )

        self.assertEqual(test_paths, [self.yml_path], "选项的值被当成了用例路径（M3）")
        self.assertIn(ini_path, remaining)
        self.assertIn("--save-tests", remaining)

    def test_equals_form_is_naturally_safe(self):
        test_paths, remaining = compat.filter_test_paths(
            [f"--rootdir={self.tmp_dir}", self.yml_path]
        )

        self.assertEqual(test_paths, [self.yml_path])
        self.assertIn(f"--rootdir={self.tmp_dir}", remaining)

    def test_multiple_test_paths_are_all_collected(self):
        second = os.path.join(self.tmp_dir, "second.yml")
        with open(second, "w", encoding="utf-8") as f:
            f.write("config:\n    name: second\n")

        test_paths, _remaining = compat.filter_test_paths([self.yml_path, second])

        self.assertEqual(test_paths, [self.yml_path, second])

    # ---------------------------------------------------------------- M3 端到端（conftest 内容）
    def _generated_summary_path(self, args, conftest_dir: str = None) -> str:
        """跑一次 conftest 生成，把生成物里**硬编码的 summary 路径**取出来。

        `conftest_dir` 默认为 `setUp` 建的项目目录；M4 那条用例的落点是
        「用例自己所在目录」，所以要把目录传进来。
        """
        compat._generate_conftest_for_summary(args)

        conftest_path = os.path.join(conftest_dir or self.tmp_dir, "conftest.py")
        with open(conftest_path, encoding="utf-8") as f:
            content = f.read()

        for line in content.splitlines():
            stripped = line.strip()
            if stripped.startswith("summary_path ="):
                raw_value = stripped.split("=", 1)[1].strip()
                # 生成物里写的是原始字符串字面量：`summary_path = r"D:\..."`
                if raw_value.startswith("r"):
                    raw_value = raw_value[1:]
                return raw_value.strip().strip('"')
        raise AssertionError(f"生成物里没有 summary_path：\n{content[:400]}")

    def test_summary_name_follows_the_case_not_the_option_value(self):
        ini_path = os.path.join(self.tmp_dir, "pytest.ini")
        with open(ini_path, "w", encoding="utf-8") as f:
            f.write("[pytest]\n")

        summary_path = self._generated_summary_path(
            ["-c", ini_path, self.yml_path, "--save-tests"]
        )

        self.assertTrue(
            summary_path.endswith(os.path.join("logs", "case.summary.json")),
            f"summary 名字跟着**选项的值**走了（M3 修复前形态）：{summary_path}",
        )

