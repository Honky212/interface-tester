class TestConfigStageFailureIsReportedAsFailure(unittest.TestCase):
    """H3 端到端：`test_start` **每个阶段**的失败都要进「用例级事实来源」。

    ## 修复前的现场（实测，真 CLI：`hrun case.yml --save-tests`，config.timeout 非法）

    ```text
    内层 pytest：1 failed、子进程退出码 1
    logs/case.summary.json：
      success = True                              ← 与退出码直接矛盾
      stat    = {'testcases': {'total': 1, 'success': 1, 'fail': 0}, ...}
      details[0].success = True
      details[0].records = []
      details[0].time.duration = 0.0
      details[0].log = <一个不存在的 .run.log 路径>
      logs/ 目录里：只有 all/case.summary.json，**一个 .run.log 都没有**
    ```

    两处根因（`runner.test_start`）：`_setup_runner` / 挂 sink / `__parse_config` 都在
    那个设 `__failed = True` 的 `try` **之外**，而 `__duration` 更是在 `finally` **之后**赋值。

    触发面很宽，且都是**用户最常见的写错**：`config.timeout` 非法、
    `config.variables` 里 `${ENV(缺失)}`、`config.base_url` 解析失败……
    """

    def setUp(self):
        loader.reset_project_meta()
        self.tmp_dir, self.yml_path = _make_tmp_project()

    def tearDown(self):
        loader.reset_project_meta()
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    def _run_save_tests(self, config_extra: str):
        with open(self.yml_path, "w", encoding="utf-8") as f:
            f.write(
                f"config:\n"
                f"    name: config stage probe\n"
                f"    base_url: {HTTP_BIN_URL}\n"
                f"{config_extra}"
                f"teststeps:\n"
                f"    -\n"
                f"        name: never runs\n"
                f"        request:\n"
                f"            method: GET\n"
                f"            url: /status/200\n"
                f"        validate:\n"
                f'            - eq: ["status_code", 200]\n'
            )

        env = dict(os.environ)
        env["PYTHONIOENCODING"] = "utf-8"
        proc = subprocess.run(
            [
                sys.executable,
                "-m",
                "interfacetester",
                "run",
                "case.yml",
                "--save-tests",
            ],
            cwd=self.tmp_dir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            timeout=180,
        )

        summary_path = os.path.join(self.tmp_dir, "logs", "case.summary.json")
        self.assertTrue(
            os.path.isfile(summary_path),
            f"summary.json 没有被生成\nreturncode={proc.returncode}\n"
            f"stdout=\n{proc.stdout}\nstderr=\n{proc.stderr}",
        )
        with open(summary_path, encoding="utf-8") as f:
            return proc, json.load(f)

    def test_bad_config_timeout_is_reported_as_failure(self):
        proc, summary = self._run_save_tests('    timeout: "not-a-number"\n')

        self.assertNotEqual(proc.returncode, 0, "配置解析失败必须是非零退出码")

        self.assertFalse(
            summary["success"],
            "配置解析阶段失败被报成通过（H3）："
            f"{json.dumps(summary, ensure_ascii=False)[:400]}",
        )
        self.assertEqual(
            summary["stat"]["testcases"],
            {"total": 1, "success": 0, "fail": 1},
            "失败用例在 stat.testcases 里必须记成 fail",
        )
        self.assertFalse(summary["details"][0]["success"])

        # 记录为空是对的（一个 step 都没跑），但**绝不能是负数**（M8 的修复前形态）
        for key, value in summary["stat"]["teststeps"].items():
            self.assertGreaterEqual(
                value,
                0,
                f"stat.teststeps.{key} 出现了负数（M8 修复前形态）："
                f"{json.dumps(summary['stat'], ensure_ascii=False)}",
            )
        self.assertEqual(summary["details"][0]["records"], [])

    def test_missing_env_variable_in_config_is_reported_as_failure(self):
        """第二形态（更常见）：`config.variables` 里引用了不存在的 ENV。"""
        proc, summary = self._run_save_tests(
            '    variables:\n        token: "${ENV(ABSENT_TOKEN_FOR_PROBE)}"\n'
        )

        self.assertNotEqual(proc.returncode, 0)
        self.assertFalse(summary["success"])
        self.assertEqual(summary["stat"]["testcases"]["fail"], 1)

    def test_failing_case_duration_is_not_zero(self):
        """M7：失败用例的耗时不能记成 0（`__duration` 原先在 `finally` 之后赋值）。

        NOTICE（为什么用 `sleep` 造一个**可测的**耗时）：`time.time()` 的分辨率有限，
        配置解析失败往往在同一时刻刻度内完成 —— `time.time() - __start_at` 可能
        **恰好等于 0.0**，于是「断言 > 0」会随机变红。这类「靠碰运气」的护栏本身就是
        新的抽风源（见 `docs/架构与调用链.md` §十 第 3 条）。
        这里在配置解析阶段里插一个 `${sleep(0.05)}`：它**先**执行、失败的 timeout 在**后**，
        因此用例级耗时必然 ≥ 0.05s，断言 `>= 0.04`（留调度余量）是确定性的。
        """
        _, summary = self._run_save_tests(
            '    variables:\n'
            '        slow: "${sleep(0.05)}"\n'
            '    timeout: "not-a-number"\n'
        )

        self.assertGreaterEqual(
            summary["details"][0]["time"]["duration"],
            0.04,
            "失败用例的 duration 恒为 0（M7 修复前形态）",
        )

    def test_summary_log_path_points_to_an_existing_file(self):
        """H3 连带：summary 里的 `log` 字段不得指向**不存在**的文件。

        修复前配置阶段失败的用例从不挂 sink → `logs/` 下一个 `.run.log` 都没有，
        而 `log` 字段照样写着那个路径。现在 sink 提前到 `__parse_config` **之前**挂，
        所以这类失败也会留下日志；万一某条路径仍然没挂上，`log` 必须是空串而不是野指针。
        """
        _, summary = self._run_save_tests('    timeout: "not-a-number"\n')

        log_path = summary["details"][0]["log"]
        if log_path:
            self.assertTrue(
                os.path.isfile(log_path),
                f"summary 里的 log 指向一个不存在的文件：{log_path}",
            )

        # 本用例的形态（配置阶段失败）必须**真的留下**日志文件
        run_logs = [
            name
            for name in os.listdir(os.path.join(self.tmp_dir, "logs"))
            if name.endswith(".run.log")
        ]
        self.assertTrue(
            run_logs,
            "配置解析阶段失败的用例也应该留下 .run.log（失败必须留证据）",
        )
