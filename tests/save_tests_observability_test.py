def _make_tmp_project(with_conftest: str = None, conftest_name: str = "conftest.py"):
    """建一个临时项目（放在 logs/ 下：已被 .gitignore 覆盖，也不会被 pytest 收集）。

    必须带 `debugtalk.py`：这样 `load_project_meta` 才能确定地把 RootDir 定位到这个目录，
    生成的 conftest.py 才会落在这里（否则会落到 cwd，也就是仓库根 —— 这正是
    缺陷汇总里 M6 的现场）。
    """
    tmp_dir = os.path.join(os.getcwd(), "logs", f"tmp_save_{uuid.uuid4().hex[:8]}")
    os.makedirs(tmp_dir)

    with open(os.path.join(tmp_dir, "debugtalk.py"), "w", encoding="utf-8") as f:
        f.write("# 项目标记：让 RootDir 稳定落在这个目录\n")
    yml_path = os.path.join(tmp_dir, "case.yml")
    with open(yml_path, "w", encoding="utf-8") as f:
        f.write(
            f"config:\n"
            f"    name: save-tests probe\n"
            f"    base_url: {HTTP_BIN_URL}\n"
            f"teststeps:\n"
            f"    -\n"
            f"        name: simple get\n"
            f"        request:\n"
            f"            method: GET\n"
            f"            url: /status/200\n"
            f"        validate:\n"
            f'            - eq: ["status_code", 200]\n'
        )

    if with_conftest is not None:
        with open(
            os.path.join(tmp_dir, conftest_name), "w", encoding="utf-8"
        ) as f:
            f.write(with_conftest)

    return tmp_dir, yml_path


def _capture_warnings(action):
    """执行 action 并返回 loguru 捕获到的 WARNING 文本列表。"""
    messages = []
    sink_id = logger.add(messages.append, level="WARNING", format="{message}")
    try:
        action()
    finally:
        logger.remove(sink_id)
    return messages


